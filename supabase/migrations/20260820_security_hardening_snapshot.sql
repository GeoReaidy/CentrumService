create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and lower(coalesce(p.role, '')) = 'admin'
  );
$$;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated, service_role;

create or replace function public.get_my_network_status()
returns table (
  node_id uuid, node_name text, monitor_enabled boolean, probe_status text,
  latency_ms integer, last_checked_at timestamptz, last_seen_at timestamptz,
  maintenance_mode boolean, maintenance_message text,
  global_maintenance boolean, monitor_heartbeat_at text
)
language sql stable security definer set search_path = '' as $$
  select p.node_id, n.name, coalesce(n.monitor_enabled,false),
    coalesce(n.probe_status,'unknown'), n.latency_ms, n.last_checked_at,
    n.last_seen_at, coalesce(n.maintenance_mode,false), n.maintenance_message,
    coalesce((select lower(s.value)='true' from public.system_settings s where s.key='global_maintenance'),false),
    nullif((select s.value from public.system_settings s where s.key='monitor_heartbeat_at'),'')
  from public.profiles p
  left join public.nodes n on n.id=p.node_id
  where p.id=(select auth.uid());
$$;
revoke all on function public.get_my_network_status() from public, anon;
grant execute on function public.get_my_network_status() to authenticated, service_role;

