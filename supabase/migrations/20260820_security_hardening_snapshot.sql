create or replace function public.guard_live_chat_session_update()
returns trigger language plpgsql set search_path='' as $$
begin
  if public.is_admin() then return new; end if;
  if auth.uid() is null or old.customer_id <> auth.uid() then raise exception 'not allowed'; end if;
  if new.id is distinct from old.id
     or new.customer_id is distinct from old.customer_id
     or new.started_at is distinct from old.started_at
     or new.updated_at is distinct from old.updated_at then
    raise exception 'only chat status can be changed';
  end if;
  if new.status <> 'closed' then raise exception 'customers may only close a live chat'; end if;
  return new;
end;
$$;
drop trigger if exists guard_live_chat_session_customer_update on public.live_chat_sessions;
create trigger guard_live_chat_session_customer_update before update on public.live_chat_sessions
for each row execute function public.guard_live_chat_session_update();

