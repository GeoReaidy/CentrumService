create or replace function public.submit_subscriber_link_request(
  p_full_name text,
  p_phone text,
  p_customer_reference text,
  p_customer_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_request_id bigint;
begin
  if v_user_id is null then raise exception 'authentication required'; end if;
  if char_length(trim(coalesce(p_full_name, ''))) not between 2 and 160 then raise exception 'enter your full name'; end if;
  if char_length(trim(coalesce(p_phone, ''))) not between 6 and 40 then raise exception 'enter a valid phone number'; end if;
  if char_length(trim(coalesce(p_customer_reference, ''))) not between 2 and 120 then raise exception 'enter your customer reference'; end if;
  if char_length(trim(coalesce(p_customer_note, ''))) > 1000 then raise exception 'note is too long'; end if;

  if exists (select 1 from public.profiles where id = v_user_id and subscription_verified) then
    raise exception 'this account is already linked';
  end if;

  insert into public.subscriber_link_requests (requester_id, full_name, phone, customer_reference, customer_note)
  values (v_user_id, trim(p_full_name), trim(p_phone), trim(p_customer_reference), nullif(trim(coalesce(p_customer_note, '')), ''))
  returning id into v_request_id;

  insert into public.notifications (recipient_id, category, event_type, title, body, href, source_type, source_id)
  select p.id, 'service_requests', 'subscriber_link_requested', 'Subscriber link request',
    trim(p_full_name) || ' submitted a subscription-link request.',
    case when p.role = 'manager' then '/manager/subscriber-links' else '/admin/subscriber-links' end,
    'subscriber_link_request', v_request_id::text
  from public.profiles p where lower(p.role) in ('admin', 'manager');

  return v_request_id;
exception
  when unique_violation then raise exception 'a link request is already pending';
end;
$$;

revoke all on function public.submit_subscriber_link_request(text, text, text, text) from public;
grant execute on function public.submit_subscriber_link_request(text, text, text, text) to authenticated;

create or replace function public.review_subscriber_link_request(
  p_request_id bigint,
  p_decision text,
  p_staff_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request public.subscriber_link_requests%rowtype;
begin
  if not public.is_staff() then raise exception 'MFA-verified staff access required'; end if;
  if p_decision not in ('approved', 'rejected') then raise exception 'invalid review decision'; end if;
  if char_length(trim(coalesce(p_staff_note, ''))) > 1000 then raise exception 'staff note is too long'; end if;

  select * into v_request from public.subscriber_link_requests
  where id = p_request_id and status = 'pending' for update;
  if not found then raise exception 'pending request not found'; end if;

  update public.subscriber_link_requests set
    status = p_decision,
    staff_note = nullif(trim(coalesce(p_staff_note, '')), ''),
    reviewed_by = auth.uid(), reviewed_at = now(), updated_at = now()
  where id = p_request_id;

  if p_decision = 'approved' then
    update public.profiles set subscription_verified = true, updated_at = now()
    where id = v_request.requester_id;
  end if;

  insert into public.notifications (recipient_id, category, event_type, title, body, href, source_type, source_id)
  values (
    v_request.requester_id,
    'service_requests',
    'subscriber_link_' || p_decision,
    case when p_decision = 'approved' then 'Subscription linked' else 'Link request needs attention' end,
    case when p_decision = 'approved'
      then 'Your Centrum subscription was linked to this portal account.'
      else 'Your subscription-link request was not approved. Open Account Settings for details.' end,
    '/portal/account#subscription-link',
    'subscriber_link_request',
    p_request_id::text
  );
end;
$$;

revoke all on function public.review_subscriber_link_request(bigint, text, text) from public;
grant execute on function public.review_subscriber_link_request(bigint, text, text) to authenticated;

comment on column public.profiles.subscription_verified is
