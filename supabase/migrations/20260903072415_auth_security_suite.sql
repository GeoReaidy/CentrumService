-- Centrum authentication security suite:
-- - staff MFA enforcement at the RLS authorization boundary
-- - customer/subscriber linking requests with staff approval
-- - trusted-browser records for new-login alerts
-- - security notifications that cannot be disabled

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'profiles' and column_name = 'subscription_verified'
  ) then
    alter table public.profiles add column subscription_verified boolean not null default false;
    -- Existing accounts predate the linking workflow and must keep their current service access.
    update public.profiles set subscription_verified = true;
  end if;
end;
$$;

alter table public.notifications drop constraint if exists notifications_category_check;
alter table public.notifications
  add constraint notifications_category_check
  check (category in ('tickets', 'announcements', 'service_requests', 'customization', 'security'));

create table if not exists public.subscriber_link_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null check (char_length(full_name) between 2 and 160),
  phone text not null check (char_length(phone) between 6 and 40),
  customer_reference text not null check (char_length(customer_reference) between 2 and 120),
  customer_note text check (customer_note is null or char_length(customer_note) <= 1000),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  staff_note text check (staff_note is null or char_length(staff_note) <= 1000),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists subscriber_link_requests_one_pending_per_user
  on public.subscriber_link_requests (requester_id) where status = 'pending';
create index if not exists subscriber_link_requests_staff_queue
  on public.subscriber_link_requests (status, created_at desc);

alter table public.subscriber_link_requests enable row level security;

drop policy if exists "Customers can read own subscriber link requests" on public.subscriber_link_requests;
create policy "Customers can read own subscriber link requests"
  on public.subscriber_link_requests for select to authenticated
  using (requester_id = (select auth.uid()));

drop policy if exists "MFA verified staff can read subscriber link requests" on public.subscriber_link_requests;
create policy "MFA verified staff can read subscriber link requests"
  on public.subscriber_link_requests for select to authenticated
  using ((select public.is_staff()));

revoke all on public.subscriber_link_requests from anon, authenticated;
grant select on public.subscriber_link_requests to authenticated;

create table if not exists public.login_devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  device_key_hash text not null check (char_length(device_key_hash) = 64),
  label text not null check (char_length(label) between 1 and 160),
  user_agent_preview text check (user_agent_preview is null or char_length(user_agent_preview) <= 240),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (user_id, device_key_hash)
);

create index if not exists login_devices_user_last_seen
  on public.login_devices (user_id, last_seen_at desc);

alter table public.login_devices enable row level security;

drop policy if exists "Users can read own login devices" on public.login_devices;
create policy "Users can read own login devices"
  on public.login_devices for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Users can forget own login devices" on public.login_devices;
create policy "Users can forget own login devices"
  on public.login_devices for delete to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.login_devices from anon, authenticated;
grant select, delete on public.login_devices to authenticated;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((auth.jwt() ->> 'aal') = 'aal2', false)
    and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and lower(coalesce(p.role, '')) = 'admin'
    );
$$;

