create or replace function private.centrum_notification_announcement_published()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_should_notify boolean := false;
begin
  if tg_op = 'INSERT' then
    v_should_notify := new.is_published and new.starts_at <= now();
  elsif tg_op = 'UPDATE' then
    v_should_notify := new.is_published and new.starts_at <= now()
      and (old.is_published is distinct from true);
  end if;

  if v_should_notify then
    insert into public.notifications(
      recipient_id, category, event_type, title, body, href, source_type, source_id
    )
    select
      p.id,
      'announcements',
      'announcement_published',
      left(new.title, 180),
      left(regexp_replace(new.body, '\s+', ' ', 'g'), 500),
      '/portal/dashboard?workspace=support&highlightAnnouncement=' || new.id,
      'announcement',
      new.id::text
    from public.profiles p
    where lower(coalesce(p.role, 'customer')) <> 'admin';
  end if;

  return new;
end;
$$;
revoke all on function private.centrum_notification_announcement_published() from public, anon, authenticated;

drop trigger if exists centrum_notification_announcement_published on public.announcements;
create trigger centrum_notification_announcement_published
after insert or update of is_published on public.announcements
for each row execute function private.centrum_notification_announcement_published();

-- Postgres Changes is used for instant in-browser delivery, with polling as a
-- fallback. Supabase's 2026 Realtime restrictions lock the realtime schema,
-- but adding a public table to the existing publication remains the supported
-- pattern.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    execute 'alter publication supabase_realtime add table public.notifications';
  end if;
end;
$$;

commit;
