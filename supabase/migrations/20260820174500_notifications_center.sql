for each row execute function private.centrum_notification_service_request_created();

create or replace function private.centrum_notification_service_request_updated()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_body text;
begin
  if new.status is distinct from old.status or new.admin_note is distinct from old.admin_note then
    v_body := 'Status: ' || initcap(replace(new.status, '_', ' '));
    if new.admin_note is not null and btrim(new.admin_note) <> '' then
      v_body := v_body || '. Centrum: ' || left(regexp_replace(new.admin_note, '\s+', ' ', 'g'), 260);
    end if;

    perform private.centrum_notify_user(
      new.customer_id,
      'service_requests',
      'service_request_updated',
      'Service request #' || new.id || ' updated',
      v_body,
      '/portal/dashboard?workspace=service&highlightRequest=' || new.id,
      'service_request',
      new.id::text || ':' || extract(epoch from now())::bigint::text
    );
  end if;
  return new;
end;
$$;
revoke all on function private.centrum_notification_service_request_updated() from public, anon, authenticated;

drop trigger if exists centrum_notification_service_request_updated on public.service_requests;
create trigger centrum_notification_service_request_updated
after update of status, admin_note on public.service_requests
for each row execute function private.centrum_notification_service_request_updated();

create or replace function private.centrum_notification_customization_created()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_body text;
begin
  v_body := new.full_name;
  if new.preferred_plan_name is not null and btrim(new.preferred_plan_name) <> '' then
    v_body := v_body || ' · Preferred plan: ' || new.preferred_plan_name;
  elsif cardinality(new.usage_types) > 0 then
    v_body := v_body || ' · ' || array_to_string(new.usage_types, ', ');
  end if;

  perform private.centrum_notify_admins(
    'customization',
    'customization_created',
    'New customization request #' || new.id,
    left(v_body, 300),
    '/admin/operations?workspace=customization&highlight=' || new.id,
    'service_customization_request',
    new.id::text
  );
  return new;
end;
$$;
revoke all on function private.centrum_notification_customization_created() from public, anon, authenticated;

