-- Centrum Service — Manager role + administrator-controlled role assignment
-- Adds a restricted operations role without weakening public.is_admin().

-- ---------------------------------------------------------------------------
-- ROLE DOMAIN
-- ---------------------------------------------------------------------------

alter table public.profiles
  drop constraint if exists profiles_role_check;

alter table public.profiles
  add constraint profiles_role_check
  check (role = any (array['customer'::text, 'manager'::text, 'admin'::text, 'support'::text]));

create or replace function public.is_manager()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(p.role, '')) = 'manager'
  );
$$;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(p.role, '')) in ('admin', 'manager')
  );
$$;

revoke all on function public.is_manager() from public, anon;
revoke all on function public.is_staff() from public, anon;
grant execute on function public.is_manager() to authenticated, service_role;
grant execute on function public.is_staff() to authenticated, service_role;

