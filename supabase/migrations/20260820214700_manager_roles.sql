-- ---------------------------------------------------------------------------
-- OPERATIONAL NOTIFICATIONS FOR MANAGERS
-- Keep the existing helper name for trigger compatibility, but deliver new
-- ticket/request/customization alerts to both administrators and managers.
-- Manager links stay inside the restricted manager workspace.
-- ---------------------------------------------------------------------------

create or replace function private.centrum_notify_admins(
  p_category text,
  p_event_type text,
  p_title text,
  p_body text,
  p_href text,
  p_source_type text default null,
  p_source_id text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.notifications(
    recipient_id, category, event_type, title, body, href, source_type, source_id
  )
  select
    p.id,
    p_category,
    p_event_type,
    left(coalesce(p_title, 'Centrum notification'), 180),
    left(coalesce(p_body, ''), 500),
    left(
      case
        when lower(coalesce(p.role, '')) = 'manager' and p_category = 'service_requests'
          then '/manager?workspace=requests'
        when lower(coalesce(p.role, '')) = 'manager' and p_category = 'customization'
          then '/manager?workspace=customization'
        when lower(coalesce(p.role, '')) = 'manager' and p_category = 'tickets'
          then coalesce(p_href, '/manager?workspace=support')
        when lower(coalesce(p.role, '')) = 'manager'
          then '/manager'
        else coalesce(p_href, '/admin')
      end,
      500
    ),
    p_source_type,
    p_source_id
  from public.profiles p
  where lower(coalesce(p.role, '')) in ('admin', 'manager');
end;
$$;

revoke all on function private.centrum_notify_admins(text,text,text,text,text,text,text) from public, anon, authenticated;
grant execute on function private.centrum_notify_admins(text,text,text,text,text,text,text) to service_role;

create or replace function private.centrum_notification_announcement_published()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_should_notify boolean := false;
begin
  if tg_op = 'INSERT' then
    v_should_notify := new.is_published and new.starts_at <= now();
  elsif tg_op = 'UPDATE' then
    v_should_notify := new.is_published and new.starts_at <= now()
      and (old.is_published is distinct from true);
  end if;

  if v_should_notify then
    insert into public.notifications(
      recipient_id, category, event_type, title, body, href, source_type, source_id
    )
    select
      p.id,
      'announcements',
      'announcement_published',
      left(new.title, 180),
      left(regexp_replace(new.body, '\\s+', ' ', 'g'), 500),
      '/portal/dashboard?workspace=support&highlightAnnouncement=' || new.id,
      'announcement',
      new.id::text
    from public.profiles p
    where lower(coalesce(p.role, 'customer')) = 'customer';
  end if;

  return new;
end;
$$;

revoke all on function private.centrum_notification_announcement_published() from public, anon, authenticated;
grant execute on function private.centrum_notification_announcement_published() to service_role;
