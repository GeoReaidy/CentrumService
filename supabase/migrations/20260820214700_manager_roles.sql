create or replace function private.centrum_guard_profile_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  -- Trusted server-side maintenance may still repair profile rows.
  if current_user in ('postgres', 'service_role', 'supabase_admin') then
    return new;
  end if;

  -- Managers may update operational customer fields, but never identity,
  -- authorization, creation metadata, or the network-node assignment.
  if public.is_manager() then
    if old.role <> 'customer' then
      raise exception 'managers may only modify customer profiles';
    end if;

    if new.id is distinct from old.id
       or new.role is distinct from old.role
       or new.created_at is distinct from old.created_at
       or new.node_id is distinct from old.node_id then
      raise exception 'managers cannot modify protected customer fields';
    end if;

    return new;
  end if;

  if new.role is distinct from old.role then
    if not public.is_admin() then
      raise exception 'only administrators can change account roles';
    end if;

    if old.id = auth.uid() then
      raise exception 'administrators cannot change their own role';
    end if;

    if old.role = 'admin' and new.role <> 'admin'
       and (select count(*) from public.profiles where role = 'admin') <= 1 then
      raise exception 'the final administrator cannot be demoted';
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.centrum_guard_profile_update() from public, anon, authenticated;
grant execute on function private.centrum_guard_profile_update() to service_role;

create or replace function private.centrum_audit_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.role is distinct from old.role then
    insert into public.role_change_audit (actor_id, target_id, old_role, new_role)
    values (auth.uid(), new.id, old.role, new.role);
  end if;
  return new;
end;
$$;

revoke all on function private.centrum_audit_profile_role_change() from public, anon, authenticated;
grant execute on function private.centrum_audit_profile_role_change() to service_role;

drop trigger if exists centrum_guard_profile_update on public.profiles;
create trigger centrum_guard_profile_update
before update on public.profiles
for each row execute function private.centrum_guard_profile_update();

drop trigger if exists centrum_audit_profile_role_change on public.profiles;
create trigger centrum_audit_profile_role_change
after update of role on public.profiles
for each row execute function private.centrum_audit_profile_role_change();

